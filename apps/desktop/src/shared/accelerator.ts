/**
 * Build an Electron accelerator string from a DOM KeyboardEvent-like object.
 * Returns null while only modifiers are held.
 */
export interface KeyLike {
  key: string;
  code: string;
  ctrlKey: boolean;
  shiftKey: boolean;
  altKey: boolean;
  metaKey: boolean;
}

const CODE_MAP: Record<string, string> = {
  PrintScreen: 'PrintScreen',
  Space: 'Space',
  Enter: 'Enter',
  Tab: 'Tab',
  Backspace: 'Backspace',
  Delete: 'Delete',
  Insert: 'Insert',
  Home: 'Home',
  End: 'End',
  PageUp: 'PageUp',
  PageDown: 'PageDown',
  ArrowUp: 'Up',
  ArrowDown: 'Down',
  ArrowLeft: 'Left',
  ArrowRight: 'Right',
  Escape: 'Escape',
  Minus: '-',
  Equal: '=',
  BracketLeft: '[',
  BracketRight: ']',
  Backslash: '\\',
  Semicolon: ';',
  Quote: "'",
  Comma: ',',
  Period: '.',
  Slash: '/',
  Backquote: '`',
  ScrollLock: 'Scrolllock',
  Pause: 'MediaPlayPause',
};

export function acceleratorFromEvent(e: KeyLike): string | null {
  const { code } = e;
  if (/^(Control|Shift|Alt|Meta|OS)(Left|Right)?$/.test(code) || ['Control', 'Shift', 'Alt', 'Meta'].includes(e.key)) {
    return null;
  }
  let key: string | undefined;
  if (/^Key[A-Z]$/.test(code)) key = code.slice(3);
  else if (/^Digit[0-9]$/.test(code)) key = code.slice(5);
  else if (/^F([1-9]|1[0-9]|2[0-4])$/.test(code)) key = code;
  else if (/^Numpad[0-9]$/.test(code)) key = 'num' + code.slice(6);
  else key = CODE_MAP[code];
  if (!key) return null;

  const mods: string[] = [];
  if (e.ctrlKey) mods.push('Control');
  if (e.altKey) mods.push('Alt');
  if (e.shiftKey) mods.push('Shift');
  if (e.metaKey) mods.push('Super');
  return [...mods, key].join('+');
}
