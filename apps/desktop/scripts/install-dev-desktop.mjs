// Dev-mode portal identity (§5): GNOME only grants global shortcuts and the
// one-time screenshot permission to an app whose desktopName matches an
// INSTALLED .desktop file. This writes one pointing at the dev launcher.
//
//   npm run install-desktop-entry            # install
//   npm run install-desktop-entry -- --remove
import { existsSync, mkdirSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

if (process.platform !== 'linux') {
  console.log('Only needed on Linux.');
  process.exit(0);
}

const APP_ID = 'works.telesto.Magpie';
const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataHome = process.env.XDG_DATA_HOME || join(homedir(), '.local/share');
const desktopFile = join(dataHome, 'applications', `${APP_ID}.desktop`);
const iconFile = join(dataHome, 'icons/hicolor/512x512/apps', `${APP_ID}.png`);

if (process.argv.includes('--remove')) {
  rmSync(desktopFile, { force: true });
  rmSync(iconFile, { force: true });
  console.log('Removed', desktopFile);
  process.exit(0);
}

const launcher = join(appDir, 'scripts', 'dev-launch.sh');
writeFileSync(
  launcher,
  `#!/bin/sh\n# Generated by install-dev-desktop.mjs: forwards to the running dev instance, or starts a built one.\ncd "${appDir}" && exec npx electron . "$@"\n`,
  { mode: 0o755 },
);

mkdirSync(dirname(desktopFile), { recursive: true });
writeFileSync(
  desktopFile,
  [
    '[Desktop Entry]',
    'Type=Application',
    'Name=Magpie (dev)',
    'Comment=Screenshot and annotate',
    `Exec="${launcher}" %F`,
    `Icon=${APP_ID}`,
    'Terminal=false',
    'Categories=Graphics;Utility;',
    'MimeType=application/x-magpie;',
    'StartupWMClass=works.telesto.Magpie',
    `X-GNOME-UsesNotifications=true`,
    'Actions=region;window;full;',
    '',
    '[Desktop Action region]',
    'Name=Capture Region',
    `Exec="${launcher}" --capture=region`,
    '',
    '[Desktop Action window]',
    'Name=Capture Window',
    `Exec="${launcher}" --capture=window`,
    '',
    '[Desktop Action full]',
    'Name=Capture Full Screen',
    `Exec="${launcher}" --capture=full`,
    '',
  ].join('\n'),
);

const icon = join(appDir, 'resources/icons/512x512.png');
if (existsSync(icon)) {
  mkdirSync(dirname(iconFile), { recursive: true });
  copyFileSync(icon, iconFile);
}
try {
  execFileSync('update-desktop-database', [join(dataHome, 'applications')], { stdio: 'ignore' });
} catch {
  /* optional */
}
console.log(`Installed ${desktopFile}\nThe id must match package.json "desktopName" (${APP_ID}.desktop).`);
